<# M3-38: inspect Windows NSIS bundle without installing or distributing it.
   Default mode validates config only. -VerifyBundle reads one generated
   installer in the repository's fixed bundle folder; never launches it. #>
[CmdletBinding()]
param([switch] $VerifyBundle)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"
$repo = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
$basePath = Join-Path $repo "src-tauri/tauri.conf.json"
$overlayPath = Join-Path $repo "src-tauri/tauri.nsis-qa.conf.json"
$cargoPath = Join-Path $repo "src-tauri/Cargo.toml"

foreach ($file in @($basePath, $overlayPath, $cargoPath)) {
    if (-not (Test-Path -LiteralPath $file -PathType Leaf)) {
        throw "nsis_bundle_qa: missing_repo_config"
    }
}
$base = Get-Content -LiteralPath $basePath -Raw | ConvertFrom-Json
$overlay = Get-Content -LiteralPath $overlayPath -Raw | ConvertFrom-Json
$cargo = Get-Content -LiteralPath $cargoPath -Raw

if ($base.bundle.active -ne $false) {
    throw "nsis_bundle_qa: production_bundle_must_be_opt_in"
}
$caps = @($base.app.security.capabilities)
if ($caps.Count -ne 1 -or $caps[0] -ne "default") {
    throw "nsis_bundle_qa: test_capability_in_production"
}
if ($cargo -notmatch '(?m)^\s*default\s*=\s*\[\s*\]\s*$') {
    throw "nsis_bundle_qa: cargo_default_features_not_empty"
}
if (@($overlay.PSObject.Properties.Name).Count -ne 1 -or
    @($overlay.PSObject.Properties.Name)[0] -ne "bundle") {
    throw "nsis_bundle_qa: unexpected_config_overlay"
}
if ($overlay.bundle.active -ne $true -or
    @($overlay.bundle.targets).Count -ne 1 -or
    @($overlay.bundle.targets)[0] -ne "nsis" -or
    @($overlay.bundle.PSObject.Properties.Name).Count -ne 2) {
    throw "nsis_bundle_qa: invalid_nsis_only_overlay"
}
Write-Output "nsis_bundle_qa: production_isolation_valid"

if (-not $VerifyBundle) {
    Write-Output "nsis_bundle_qa: config_only_no_installer_executed"
    return
}
if ($env:OS -ne "Windows_NT") {
    throw "nsis_bundle_qa: windows_required"
}

$bundleFolder = Join-Path $repo "src-tauri/target/release/bundle/nsis"
if (-not (Test-Path -LiteralPath $bundleFolder -PathType Container)) {
    throw "nsis_bundle_qa: no_nsis_output"
}
$installers = @(Get-ChildItem -LiteralPath $bundleFolder -Filter "*.exe" -File |
    Where-Object { $_.Name -match '(?i)^aiimage.*-setup\.exe$' -or $_.Name -match '(?i)^aiimage.*_setup\.exe$' })
if ($installers.Count -ne 1) {
    throw "nsis_bundle_qa: unexpected_installer_count"
}
$installer = $installers[0]
if ($installer.Length -lt 100000 -or
    (($installer.Attributes -band [System.IO.FileAttributes]::ReparsePoint) -ne 0)) {
    throw "nsis_bundle_qa: invalid_installer_file"
}
$stream = [System.IO.File]::OpenRead($installer.FullName)
try {
    if ($stream.ReadByte() -ne 77 -or $stream.ReadByte() -ne 90) {
        throw "nsis_bundle_qa: invalid_pe_signature"
    }
} finally {
    $stream.Dispose()
}
# The hash is evidence of generated bytes, not an authenticity signature.
$hash = (Get-FileHash -LiteralPath $installer.FullName -Algorithm SHA256).Hash
if ($hash -notmatch '^[A-F0-9]{64}$') {
    throw "nsis_bundle_qa: sha256_unavailable"
}
Write-Output "nsis_bundle_qa: unsigned_installer_generated_not_distributed"
Write-Output ("nsis_bundle_qa: sha256=" + $hash)
